  INDEX idx_finance_reconciliation_difference_payment_status (payment_order_id,status,id),
  INDEX idx_finance_reconciliation_difference_refund_status (refund_order_id,status,id),
  INDEX idx_finance_reconciliation_difference_order_status (order_id,status,id),
  INDEX idx_finance_reconciliation_external_refund (external_refund_applied,status,id),
  CONSTRAINT fk_finance_reconciliation_difference_batch FOREIGN KEY (batch_id) REFERENCES finance_reconciliation_batch (id) ON DELETE RESTRICT,
