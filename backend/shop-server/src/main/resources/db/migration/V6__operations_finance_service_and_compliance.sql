  CONSTRAINT fk_finance_reconciliation_difference_payment FOREIGN KEY (payment_order_id) REFERENCES payment_order (id) ON DELETE SET NULL,
  CONSTRAINT fk_finance_reconciliation_difference_refund FOREIGN KEY (refund_order_id) REFERENCES refund_order (id) ON DELETE SET NULL,
  CONSTRAINT chk_finance_reconciliation_difference_candidate CHECK ((((candidate_content_sha256 = '') and (candidate_storage_provider = '') and (candidate_storage_container = '') and (candidate_storage_region = '') and (candidate_object_key = '') and (candidate_size_bytes is null)) or ((difference_type = 'SOURCE_CHANGED') and (char_length(candidate_content_sha256) = 64) and (candidate_storage_provider <> '') and (candidate_storage_container <> '') and (candidate_object_key <> '') and (candidate_size_bytes is not null) and (candidate_size_bytes >= 0)))),
  CONSTRAINT chk_finance_reconciliation_difference_severity CHECK ((severity in ('INFO','WARNING','CRITICAL'))),
  CONSTRAINT chk_finance_reconciliation_difference_status CHECK ((status in ('OPEN','INVESTIGATING','RESOLVED','AUTO_CLEARED'))),
  CONSTRAINT chk_finance_reconciliation_difference_type CHECK ((difference_type in ('CHANNEL_ONLY','LOCAL_ONLY','AMOUNT_MISMATCH','IDENTITY_MISMATCH','STATUS_MISMATCH','DUPLICATE_CHANNEL_ROW','SOURCE_CHANGED')))
);

