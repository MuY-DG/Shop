  config_name varchar(80) NOT NULL,
  app_id varchar(64) NOT NULL,
  mch_id varchar(32) NOT NULL,
  merchant_serial_no varchar(128) NOT NULL,
  api_v3_key_ciphertext text NOT NULL,
  verify_mode varchar(32) NOT NULL DEFAULT 'PUBLIC_KEY',
  wechat_public_key_id varchar(128) NOT NULL DEFAULT '',
  notify_url varchar(255) NOT NULL,
  refund_notify_url varchar(255) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT FALSE,
  status varchar(20) NOT NULL DEFAULT 'ACTIVE',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  secret_cipher_version smallint NOT NULL DEFAULT 2,
  secret_key_id varchar(64) NOT NULL DEFAULT '',
  secret_revision bigint NOT NULL DEFAULT '0',
  secret_reencrypted_at timestamp NULL DEFAULT NULL,
  private_key_pem_ciphertext text,
  wechat_public_key_pem_ciphertext text,
  deleted_at timestamp NULL DEFAULT NULL,
  deleted_by bigint DEFAULT NULL,
  PRIMARY KEY (id),
  INDEX idx_payment_config_secret_key (secret_cipher_version,secret_key_id,id),
  CONSTRAINT chk_payment_config_cipher_v2 CHECK (secret_cipher_version = 2 AND secret_key_id <> ''),
  CONSTRAINT chk_payment_config_delete_state CHECK ((((status = 'ACTIVE') and (deleted_at is null) and (deleted_by is null)) or ((status = 'DELETED') and (enabled = false) and (deleted_at is not null) and (deleted_by is not null) and (deleted_by > 0))))
);

