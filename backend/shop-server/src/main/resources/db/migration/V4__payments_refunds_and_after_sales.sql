-- Shop schema generation 2 baseline.
-- Database-only payment configuration, payments, refunds, and after-sales.

CREATE TABLE after_sale_evidence (
  id bigint NOT NULL AUTO_INCREMENT,
  after_sale_id bigint NOT NULL,
  file_id bigint NOT NULL,
  sort_order int NOT NULL DEFAULT '0',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  INDEX idx_after_sale_evidence_after_sale_sort (after_sale_id,sort_order,id)
);

CREATE TABLE after_sale_item (
  id bigint NOT NULL AUTO_INCREMENT,
  after_sale_id bigint NOT NULL,
  order_item_id bigint NOT NULL,
  sku_id bigint NOT NULL,
  order_quantity_snapshot int NOT NULL,
  paid_amount_basis_cent bigint NOT NULL,
  refunded_quantity_before int NOT NULL DEFAULT '0',
  requested_quantity int NOT NULL,
  approved_quantity int DEFAULT NULL,
  requested_amount_cent bigint NOT NULL,
  approved_amount_cent bigint DEFAULT NULL,
  restock_quantity int NOT NULL DEFAULT '0',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_after_sale_item_sale_order_item UNIQUE (after_sale_id,order_item_id),
  INDEX idx_after_sale_item_order_item_sale (order_item_id,after_sale_id),
  CONSTRAINT chk_after_sale_item_amounts CHECK (((paid_amount_basis_cent >= 0) and (requested_amount_cent >= 0) and (requested_amount_cent <= paid_amount_basis_cent) and ((approved_amount_cent is null) or ((approved_amount_cent >= 0) and (approved_amount_cent <= requested_amount_cent) and (approved_amount_cent <= paid_amount_basis_cent))))),
  CONSTRAINT chk_after_sale_item_quantities CHECK (((order_quantity_snapshot > 0) and (refunded_quantity_before >= 0) and (refunded_quantity_before <= order_quantity_snapshot) and (requested_quantity > 0) and (requested_quantity <= (order_quantity_snapshot - refunded_quantity_before)) and ((approved_quantity is null) or ((approved_quantity >= 0) and (approved_quantity <= requested_quantity))) and (restock_quantity >= 0) and (restock_quantity <= coalesce(approved_quantity,0))))
);

