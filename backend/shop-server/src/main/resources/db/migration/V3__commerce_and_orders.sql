-- Shop schema generation 2 baseline.
-- Cart, coupons, inventory, analytics, and order aggregates.

CREATE TABLE analytics_event (
  id bigint NOT NULL AUTO_INCREMENT,
  client_event_id varchar(64) NOT NULL,
  payload_digest varchar(64) NOT NULL,
  visitor_id varchar(64) NOT NULL,
  session_id varchar(64) NOT NULL,
  user_id bigint DEFAULT NULL,
  event_source varchar(16) NOT NULL,
  event_type varchar(32) NOT NULL,
  page_path varchar(160) NOT NULL DEFAULT '',
  source_page varchar(160) NOT NULL DEFAULT '',
  entry_scene varchar(32) NOT NULL DEFAULT '',
  search_keyword varchar(80) NOT NULL DEFAULT '',
  checkout_source varchar(20) NOT NULL DEFAULT '',
  spu_id bigint DEFAULT NULL,
  sku_id bigint DEFAULT NULL,
  quantity int DEFAULT NULL,
  occurred_at timestamp NOT NULL,
  received_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  business_date date NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_analytics_event_visitor_client UNIQUE (visitor_id,client_event_id),
  INDEX idx_analytics_event_date_type (business_date,event_type,id),
  INDEX idx_analytics_event_user_date (user_id,business_date,id),
  INDEX idx_analytics_event_session_time (visitor_id,session_id,occurred_at,id),
  INDEX idx_analytics_event_spu_type_date (spu_id,event_type,business_date,id),
  INDEX idx_analytics_event_received (received_at,id),
  INDEX idx_analytics_event_retention (business_date,id)
);

CREATE TABLE cart_item (
  id bigint NOT NULL AUTO_INCREMENT,
  user_id bigint NOT NULL,
  sku_id bigint NOT NULL,
  quantity int NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_cart_item_user_sku UNIQUE (user_id,sku_id),
  INDEX idx_cart_item_user_updated (user_id,updated_at),
  INDEX idx_cart_item_sku (sku_id),
  INDEX idx_cart_item_updated (updated_at,id)
);

CREATE TABLE coupon_claim_record (
  id bigint NOT NULL AUTO_INCREMENT,
  template_id bigint NOT NULL,
  user_id bigint NOT NULL,
  user_coupon_id bigint NOT NULL,
  claimed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  issue_source varchar(20) NOT NULL DEFAULT 'SELF_CLAIM',
  issued_by_admin_user_id bigint DEFAULT NULL,
  issue_note varchar(200) NOT NULL DEFAULT '',
  PRIMARY KEY (id),
  INDEX idx_coupon_claim_template_user (template_id,user_id,claimed_at),
  INDEX idx_coupon_claim_issue_source (issue_source,claimed_at,id),
  INDEX idx_coupon_claim_claimed (claimed_at,id)
);

CREATE TABLE coupon_template (
  id bigint NOT NULL AUTO_INCREMENT,
  name varchar(80) NOT NULL,
  description varchar(255) NOT NULL DEFAULT '',
  coupon_type varchar(20) NOT NULL,
  discount_type varchar(20) NOT NULL,
  threshold_cent bigint NOT NULL DEFAULT '0',
  discount_cent bigint NOT NULL,
  scope_type varchar(20) NOT NULL DEFAULT 'ALL',
  scope_value varchar(255) NOT NULL DEFAULT '',
  strategy_key varchar(80) NOT NULL DEFAULT 'coupon.amount-off.v1',
  total_stock int NOT NULL,
  claimed_count int NOT NULL DEFAULT '0',
  per_user_limit int NOT NULL DEFAULT '1',
  valid_start_at timestamp NOT NULL,
  valid_end_at timestamp NOT NULL,
  status varchar(20) NOT NULL,
  sort_order int NOT NULL DEFAULT '0',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  distribution_mode varchar(20) NOT NULL DEFAULT 'PUBLIC',
  audience_user_id bigint DEFAULT NULL,
  PRIMARY KEY (id),
  INDEX idx_coupon_template_status_sort (status,sort_order,id),
  INDEX idx_coupon_template_validity (valid_start_at,valid_end_at),
  INDEX idx_coupon_template_distribution_audience (distribution_mode,audience_user_id,id)
);

CREATE TABLE order_item (
  id bigint NOT NULL AUTO_INCREMENT,
  order_id bigint NOT NULL,
  sku_id bigint NOT NULL,
  spu_id bigint NOT NULL,
  product_title varchar(128) NOT NULL,
  product_subtitle varchar(255) NOT NULL DEFAULT '',
  main_image varchar(500) NOT NULL DEFAULT '',
  sku_image varchar(500) NOT NULL DEFAULT '',
  display_image varchar(500) NOT NULL DEFAULT '',
  sku_code varchar(64) NOT NULL,
  spec_text varchar(255) NOT NULL DEFAULT '',
  original_price_cent bigint NOT NULL DEFAULT '0',
  unit_price_cent bigint NOT NULL DEFAULT '0',
  quantity int NOT NULL,
  line_original_amount_cent bigint NOT NULL DEFAULT '0',
  line_amount_cent bigint NOT NULL DEFAULT '0',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  main_image_file_id bigint DEFAULT NULL,
  sku_image_file_id bigint DEFAULT NULL,
  display_image_file_id bigint DEFAULT NULL,
  unit_cost_cent bigint DEFAULT NULL,
  line_cost_cent bigint DEFAULT NULL,
  coupon_discount_allocated_cent bigint DEFAULT NULL,
  freight_allocated_cent bigint DEFAULT NULL,
  paid_amount_allocated_cent bigint DEFAULT NULL,
  retail_unit_price_cent bigint NOT NULL DEFAULT '0',
  wholesale_tier_min_quantity int DEFAULT NULL,
  refunded_quantity int NOT NULL DEFAULT '0',
  PRIMARY KEY (id),
  INDEX idx_order_item_order (order_id),
  INDEX idx_order_item_spu (spu_id),
  INDEX idx_order_item_statistics_spu_order (spu_id,order_id,sku_id),
  INDEX idx_order_item_sku_order (sku_id,order_id),
  CONSTRAINT chk_order_item_refunded_quantity CHECK (((refunded_quantity >= 0) and (refunded_quantity <= quantity)))
);

