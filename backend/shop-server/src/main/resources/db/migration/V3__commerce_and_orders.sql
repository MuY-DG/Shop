  INDEX idx_shop_order_user_status_created (user_id,status,created_at),
  INDEX idx_shop_order_admin_status_created (status,created_at,id),
  INDEX idx_shop_order_admin_receiver_phone (receiver_phone),
  INDEX idx_shop_order_statistics_paid (paid_at,user_id,id),
  INDEX idx_shop_order_paid_at (paid_at,id),
  INDEX idx_shop_order_user_paid_at (user_id,paid_at,id),
  INDEX idx_shop_order_analytics_session (analytics_visitor_id,analytics_session_id,id),
  INDEX idx_shop_order_statistics_created (created_at,id),
  INDEX idx_shop_order_user_app_visible_created (user_id,app_deleted_at,created_at,id),
  INDEX idx_shop_order_cleanup_candidate (updated_at,id),
  INDEX idx_shop_order_created_timeout (status,payment_expires_at,id),
  INDEX idx_shop_order_refund_status_updated (refund_status,updated_at,id),
  CONSTRAINT chk_shop_order_refunded_amount CHECK (((refunded_amount_cent >= 0) and (refunded_amount_cent <= paid_amount_cent)))
);

CREATE TABLE stock_lock (
  id bigint NOT NULL AUTO_INCREMENT,
