  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paid_at timestamp NULL DEFAULT NULL,
  shipped_at timestamp NULL DEFAULT NULL,
  completed_at timestamp NULL DEFAULT NULL,
  refunding_at timestamp NULL DEFAULT NULL,
  refunded_at timestamp NULL DEFAULT NULL,
  checkout_request_digest varchar(64) NOT NULL,
  analytics_visitor_id varchar(64) DEFAULT NULL,
  analytics_session_id varchar(64) DEFAULT NULL,
  analytics_entry_scene varchar(32) NOT NULL DEFAULT '',
  app_deleted_at timestamp NULL DEFAULT NULL,
  receiver_province varchar(64) NOT NULL DEFAULT '',
