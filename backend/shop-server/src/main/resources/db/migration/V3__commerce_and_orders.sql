  order_item_id bigint NOT NULL,
  sku_id bigint NOT NULL,
  quantity int NOT NULL,
  status varchar(20) NOT NULL,
  locked_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  released_at timestamp NULL DEFAULT NULL,
