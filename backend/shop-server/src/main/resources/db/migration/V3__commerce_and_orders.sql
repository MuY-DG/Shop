  PRIMARY KEY (id),
  INDEX idx_stock_lock_order (order_id,status),
  INDEX idx_stock_lock_restock_refund (restock_refund_order_id,id),
  CONSTRAINT chk_stock_lock_restocked_quantity CHECK (((restocked_quantity >= 0) and (restocked_quantity <= quantity)))
