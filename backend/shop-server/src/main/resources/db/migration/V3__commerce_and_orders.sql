  receiver_district varchar(64) NOT NULL DEFAULT '',
  receiver_detail_address varchar(512) NOT NULL DEFAULT '',
  receiver_location_name varchar(128) NOT NULL DEFAULT '',
  receiver_doorplate varchar(128) NOT NULL DEFAULT '',
